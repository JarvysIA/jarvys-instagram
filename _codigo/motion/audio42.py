W0 = [0, 0.32, 0.48, 1.12, 1.36, 2.08, 2.16, 2.48, 2.88, 3.2, 3.44, 3.8, 4.6, 4.72, 5.08, 5.2, 5.4, 6.2, 6.4, 6.72, 7.76, 7.92, 8.4, 8.72, 8.8, 9.24, 9.6, 9.707, 10.52, 11.68, 11.84, 12.16, 12.4, 13.32, 13.52, 13.84, 14.48, 14.72, 15.52, 15.627, 15.68, 16.32, 16.4, 16.48, 16.92, 18, 18.16, 18.32, 18.76, 18.84, 18.96, 19.2, 20, 20.4, 21.08, 21.44, 22.2, 22.48, 22.6, 22.8, 23, 23.8, 23.96, 24.133, 24.92, 25.24]
W = [w + .5 for w in W0]
pop(.2, 600, .45); pop(.35, 700, .3); thump(W[3] - .1, .9)
whoosh(2.55, .6, .8); pop(W[10], 520, .4); pop(W[16], 760, .4); ding(W[16] + .15, .3); pop(W[17], 700, .35)
whoosh(8.15, .6, .8); pop(8.45, 600, .3); pop(8.7, 640, .3); pop(W[22], 480, .35); pop(W[27], 820, .45); thump(W[28], .7)
whoosh(12.1, .6, .8); [pop(W[34] + .18 * k, 600 + 60 * k, .35) for k in range(3)]; pop(W[35] + .1, 760, .35); thump(W[37], .45); pop(W[37], 480, .4)
whoosh(16.15, .6, .8); pop(W[44], 700, .4); pop(W[45], 820, .35); pop(W[46], 760, .4); ding(W[48], .3); riser(W[52], W[54], .35); thump(W[54], .8)
whoosh(22.7, .6, .8); whoosh(W[56] + .4, .5, .5); pop(W[57], 700, .35)
whoosh(24.3, .6, .8); pop(W[63], 700, .4); pop(W[63] + .25, 760, .4); bubble(W[64] - .1, True, .7)
whoosh(27.05, .7, .6); pop(27.3, 640, .55); pop(27.7, 700, .45); ding(28.9, .35)
sfx /= np.abs(sfx).max() + 1e-9
wavfile.write(f'{OUT}/sfx.wav', SR, (np.stack([sfx, sfx], 1) * 32000 * 0.9).astype(np.int16))
